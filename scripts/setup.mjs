#!/usr/bin/env node
/**
 * One place to set up a copy of the starter: GitHub settings and third-party services.
 *
 *   node scripts/setup.mjs                      What is configured, what is optional, how to turn it on
 *   node scripts/setup.mjs repo [--dry-run]     Apply the GitHub settings a template copy does not inherit
 *        [--accessibility off]                  ... with the WCAG 2.2 AA checks off (on by default; see ADR-0011)
 *   node scripts/setup.mjs set <KEY> --env Syst Save a setting (Dev: .env.local; Syst/Prod: GitHub Environment)
 *   node scripts/setup.mjs ios-xcconfig         Print apps/ios/Config/Secrets.xcconfig (used by `make generate`)
 *
 * The list of services lives in config/integrations.json and the GitHub settings in config/repo-settings.json.
 * Values never go into the repository: Dev values live in the git-ignored .env.local at the repo root, and
 * SYST and Prod values live in GitHub Environments, where deploy workflows read them as environment variables.
 * Needs the GitHub CLI (`gh auth login`) for anything that talks to GitHub.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const ENV_FILE = join(ROOT, '.env.local');

export function loadJson(path) {
  return JSON.parse(readFileSync(join(ROOT, path), 'utf8'));
}

/** Parses KEY=value lines; ignores comments and blank lines; strips matching quotes. */
export function parseEnv(text) {
  const values = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#') || !line.includes('=')) continue;
    const key = line.slice(0, line.indexOf('=')).trim();
    let value = line.slice(line.indexOf('=') + 1).trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    values[key] = value;
  }
  return values;
}

/** Sets or replaces one KEY=value line, keeping everything else (comments included). */
export function upsertEnv(text, key, value) {
  const line = `${key}=${value}`;
  const lines = text.split('\n');
  const index = lines.findIndex((l) => l.includes('=') && l.slice(0, l.indexOf('=')).trim() === key);
  if (index > -1) {
    lines[index] = line;
    return lines.join('\n');
  }
  return `${text}${text && !text.endsWith('\n') ? '\n' : ''}${line}\n`;
}

/** xcconfig treats `//` as a comment, so URLs are written as `https:/$()/host`. */
export function xcconfigValue(value) {
  return value.replace(/\/\//g, '/$()/');
}

export function iosXcconfig(values) {
  return [
    '// Generated by `node scripts/setup.mjs ios-xcconfig` (make generate). Do not edit or commit.',
    '// Values come from environment variables, or .env.local at the repository root.',
    `SENTRY_DSN = ${xcconfigValue(values.SENTRY_DSN_IOS ?? '')}`,
    '',
  ].join('\n');
}

/** Environment variables win over .env.local, like in CI and deploy workflows. */
export function localValues(env = process.env, file = ENV_FILE) {
  const fromFile = existsSync(file) ? parseEnv(readFileSync(file, 'utf8')) : {};
  const fromEnv = Object.fromEntries(Object.entries(env).filter(([, v]) => v));
  return { ...fromFile, ...fromEnv };
}

/** Rows for the status table: one per setting and environment. */
export function statusRows(registry, local, github) {
  const rows = [];
  for (const integration of registry.integrations) {
    for (const setting of integration.settings) {
      for (const environment of registry.environments) {
        const used = setting.environments.includes(environment);
        let state = 'not used';
        if (used && environment === 'Dev') state = local[setting.key] ? 'set in .env.local' : 'off';
        if (used && environment !== 'Dev') {
          const names = github?.[environment];
          state = names === undefined ? 'unknown (sign in with gh as an admin)' : names.has(setting.key) ? 'set in GitHub' : 'off';
        }
        rows.push({ integration: integration.name, key: setting.key, environment, state });
      }
    }
  }
  return rows;
}

function gh(args, input) {
  const result = spawnSync('gh', args, { input, encoding: 'utf8' });
  if (result.error) return { ok: false, out: '', err: 'GitHub CLI (gh) is not installed' };
  return { ok: result.status === 0, out: result.stdout.trim(), err: result.stderr.trim() };
}

function repository() {
  const result = gh(['repo', 'view', '--json', 'nameWithOwner', '-q', '.nameWithOwner']);
  return result.ok ? result.out : null;
}

function githubNames(repo, environments) {
  if (!repo) return undefined;
  const names = {};
  for (const environment of environments.filter((e) => e !== 'Dev')) {
    let set = new Set();
    for (const kind of ['secrets', 'variables']) {
      const result = gh(['api', `repos/${repo}/environments/${environment}/${kind}`, '--jq', `.${kind}[].name`]);
      if (result.ok) result.out.split('\n').filter(Boolean).forEach((name) => set?.add(name));
      // 404: the environment does not exist yet, so nothing is set. Anything else: we cannot tell.
      else if (!/404|Not Found/i.test(result.err)) set = undefined;
    }
    names[environment] = set;
  }
  return names;
}

function status() {
  const registry = loadJson('config/integrations.json');
  const repo = repository();
  const rows = statusRows(registry, localValues(), githubNames(repo, registry.environments));
  console.log(`Third-party services${repo ? ` for ${repo}` : ''}. All are optional; the product works without them.\n`);
  for (const integration of registry.integrations) {
    console.log(`${integration.name} (${integration.when === 'publish' ? 'when you publish' : 'optional'}, ${integration.cost})`);
    console.log(`  ${integration.purpose}`);
    for (const setting of integration.settings) {
      const states = rows
        .filter((r) => r.key === setting.key && r.state !== 'not used')
        .map((r) => `${r.environment}: ${r.state}`)
        .join(', ');
      console.log(`  ${setting.key.padEnd(30)} ${states}`);
    }
    integration.steps.forEach((step, i) => console.log(`  ${i + 1}. ${step}`));
    console.log(`  Sign up: ${integration.signUp}\n  Guide:   ${integration.guide}\n`);
  }
  const local = Object.keys(localValues({})).filter((key) => registry.integrations.some((i) => i.settings.some((s) => s.key === key)));
  console.log(`Local builds read .env.local: ${local.length ? local.join(', ') : 'nothing set'}.`);
  console.log('Turn one on:  node scripts/setup.mjs set SENTRY_DSN_IOS --env Prod');
  if (!repo) console.log('Sign in to the GitHub CLI (gh auth login) to see what is set in GitHub.');
}

async function set(key, environment, value) {
  const registry = loadJson('config/integrations.json');
  const setting = registry.integrations.flatMap((i) => i.settings).find((s) => s.key === key);
  if (!setting) throw new Error(`Unknown setting ${key}. See config/integrations.json.`);
  if (!registry.environments.includes(environment)) throw new Error(`--env must be one of ${registry.environments.join(', ')}`);

  if (environment === 'Dev') {
    const text = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8') : '';
    writeFileSync(ENV_FILE, upsertEnv(text, key, value ?? (await ask(`${setting.label}: `))));
    console.log(`Saved ${key} in .env.local (not committed).`);
    return;
  }

  const repo = repository();
  if (!repo) throw new Error('Sign in with `gh auth login` first.');
  gh(['api', '-X', 'PUT', `repos/${repo}/environments/${environment}`]);
  const kind = setting.secret ? 'secret' : 'variable';
  const args = [kind, 'set', key, '--env', environment, '--repo', repo];
  // Secrets: let gh prompt without echoing, unless a value was passed.
  const result = value || kind === 'variable'
    ? spawnSync('gh', [...args, '--body', value ?? (await ask(`${setting.label}: `))], { stdio: 'inherit' })
    : spawnSync('gh', args, { stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`Could not save ${key}.`);
  console.log(`Saved ${key} as a ${kind} in the ${environment} environment of ${repo}.`);
}

async function ask(question) {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const answer = await rl.question(question);
  rl.close();
  return answer.trim();
}

/**
 * The GitHub API calls behind `setup.mjs repo`, as [description, method, path, body].
 * Accessibility checks are on unless `accessibility` is "off": the ACCESSIBILITY_CHECKS repository variable
 * switches them in every workflow, and the required **Accessibility checks** job is then skipped, not blocking.
 */
export function repoSteps(repo, settings, environments, { accessibility = 'on' } = {}) {
  if (!['on', 'off'].includes(accessibility)) throw new Error('--accessibility must be on or off');
  return [
    ['Merge options, auto-merge, Discussions', 'PATCH', `repos/${repo}`, settings.repository],
    ['Secret scanning and push protection', 'PATCH', `repos/${repo}`, {
      security_and_analysis: { secret_scanning: { status: 'enabled' }, secret_scanning_push_protection: { status: 'enabled' } },
    }],
    ['Dependabot alerts', 'PUT', `repos/${repo}/vulnerability-alerts`, null],
    ['Dependabot security updates', 'PUT', `repos/${repo}/automated-security-fixes`, null],
    ['Private vulnerability reporting', 'PUT', `repos/${repo}/private-vulnerability-reporting`, null],
    ['CodeQL default setup', 'PATCH', `repos/${repo}/code-scanning/default-setup`, { state: 'configured' }],
    ['Read-only default token for workflows', 'PUT', `repos/${repo}/actions/permissions/workflow`, {
      default_workflow_permissions: 'read', can_approve_pull_request_reviews: false,
    }],
    ['GitHub Pages from Actions', 'POST', `repos/${repo}/pages`, { build_type: 'workflow' }],
    ...environments.map((environment) => [`Environment ${environment}`, 'PUT', `repos/${repo}/environments/${environment}`, null]),
    ...settings.labels.map(([name, color, description]) => [`Label ${name}`, 'LABEL', name, { color, description }]),
    [`Accessibility checks ${accessibility}`, 'VARIABLE', 'ACCESSIBILITY_CHECKS', accessibility],
    ['Ruleset "Protect main"', 'RULESET', `repos/${repo}/rulesets`, settings.ruleset],
  ];
}

function applyStep(repo, [description, method, path, body]) {
  if (method === 'LABEL') {
    return gh(['label', 'create', path, '--repo', repo, '--force', '--color', body.color, '--description', body.description]);
  }
  if (method === 'VARIABLE') {
    return gh(['variable', 'set', path, '--repo', repo, '--body', body]);
  }
  if (method === 'RULESET') {
    const existing = gh(['api', path, '--jq', `.[] | select(.name == "${body.name}") | .id`]);
    const id = existing.ok && existing.out ? existing.out.split('\n')[0] : null;
    return gh(['api', '-X', id ? 'PUT' : 'POST', id ? `${path}/${id}` : path, '--input', '-'], JSON.stringify(body));
  }
  const args = ['api', '-X', method, path];
  return body ? gh([...args, '--input', '-'], JSON.stringify(body)) : gh(args);
}

function repo(dryRun, options) {
  const name = repository() ?? (dryRun ? '<owner>/<repo>' : null);
  if (!name) throw new Error('Sign in with `gh auth login` (as an admin of the repository) first.');
  const settings = loadJson('config/repo-settings.json');
  const { environments } = loadJson('config/integrations.json');
  let failed = 0;
  console.log(`${dryRun ? 'Would apply' : 'Applying'} GitHub settings to ${name}:`);
  for (const step of repoSteps(name, settings, environments, options)) {
    if (dryRun) {
      console.log(`  - ${step[0]}`);
      continue;
    }
    const result = applyStep(name, step);
    // Pages and some security features answer 409/422 when already on; that is fine.
    const already = /409|422|already/i.test(result.err);
    if (!result.ok && !already) failed++;
    console.log(`  ${result.ok || already ? 'ok  ' : 'FAIL'} ${step[0]}${result.ok || already ? '' : ` (${result.err.split('\n')[0]})`}`);
  }
  if (failed) {
    console.log(`\n${failed} step(s) failed. Some need an admin token or a paid plan for private repositories; set them by hand in Settings.`);
    process.exitCode = 1;
  }
}

async function main() {
  const [command = 'status', ...rest] = process.argv.slice(2);
  const option = (name) => (rest.includes(`--${name}`) ? rest[rest.indexOf(`--${name}`) + 1] : undefined);
  if (command === 'status') return status();
  if (command === 'repo') return repo(rest.includes('--dry-run'), { accessibility: option('accessibility') ?? 'on' });
  if (command === 'set') return set(rest[0], option('env') ?? 'Dev', option('value'));
  if (command === 'ios-xcconfig') return process.stdout.write(iosXcconfig(localValues()));
  console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('*/')[0]);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
